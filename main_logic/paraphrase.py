"""Paraphrase clusters (spec v0.3, section 7.1; pipeline step 1).

A cluster is one original question plus two paraphrases that ask exactly the same thing. The
paraphrases are generated by the generator LLM and kept only if they pass three gates:

  1. NLI: the original entails the paraphrase AND the paraphrase entails the original
     (DeBERTa-MNLI; "entails" = ENTAILMENT is the most probable of the three labels);
  2. cosine >= 0.75 between the two questions' sentence embeddings (all-mpnet-base-v2). The
     spec says 0.85; at 0.85 only 6 of 20 NQ pilot clusters were complete, and the rejected
     candidates were mostly good paraphrases of short questions, so the user lowered it (Oct 10);
  3. answer preservation: a gold answer that is not in the original question must not appear
     verbatim in the paraphrase (the paraphrase must not give the answer away).

Protocol (user decisions, Oct 10, 2026): questions sampled with seed 42 from NQ-open dev and
HotpotQA dev; Llama 3.1 8B Instruct writes 5 candidates per question at temperature 0.7; the
first 2 candidates, in generation order, that pass all gates join the cluster. A question with
fewer than 2 passing candidates gives an incomplete cluster, which is kept on disk, skipped by
calibration and counted. Back-translation (in section 7.1) is dropped by the user. The prompt
asks for different words or sentence structure: the first wording ("Rewrite this question so it
asks exactly the same thing ...") made the model only fix capitalization (DECISIONS.md).

torch and transformers are imported only by the model functions, so the logic and its tests run
without them.
"""

import numpy as np

from main_logic import answers as an

PROMPT = ("Paraphrase this question: reword it using different words or sentence structure so "
          "that it still asks exactly the same thing. Do not add or remove information and do "
          "not include the answer.")
N_CANDIDATES = 5
TEMPERATURE = 0.7
MAX_TOKENS = 64
SEED = 42               # question sample and the first candidate's seed (candidate i: SEED + i)
PER_CLUSTER = 2         # paraphrases per cluster, so 3 phrasings with the original
COSINE_MIN = 0.75     # spec 7.1 says 0.85; lowered by the user Oct 10 (DECISIONS.md)

NLI_MODEL = "microsoft/deberta-large-mnli"
NLI_REVISION = "7296194b9009373def4f7c5dad292651e4b5cf4e"
EMBED_MODEL = "sentence-transformers/all-mpnet-base-v2"
EMBED_REVISION = "e8c3b32edf5434bc2275fc9bab85f82640a19130"

_LABELS = ("rewritten question:", "rewrite:", "paraphrase:", "question:")


def sample(n_total, n, seed=SEED):
    """Indices of n questions out of n_total, in sampled order (a seeded permutation, cut at n).

    Taking a prefix of one permutation means a smaller sample (the 20-question pilot) is always
    the start of a larger one (the 300-question run).
    """
    if n > n_total:
        raise ValueError(f"cannot sample {n} of {n_total} questions")
    return [int(i) for i in np.random.default_rng(seed).permutation(n_total)[:n]]


def messages(question):
    """The chat messages that ask the LLM for one paraphrase."""
    return [{"role": "user",
             "content": f"{PROMPT}\n\nQuestion: {question}\n\nReply with the rewritten question only."}]


def clean(text):
    """The paraphrase in an LLM reply: first non-empty line, a leading label such as
    "Rewritten question:" removed, surrounding quotes removed. "" if nothing is left."""
    lines = [line.strip() for line in (text or "").splitlines() if line.strip()]
    if not lines:
        return ""
    s = lines[0]
    if s.lower().startswith(_LABELS):
        s = s.split(":", 1)[1].strip()
    while len(s) >= 2 and s[0] == s[-1] and s[0] in "\"'":
        s = s[1:-1].strip()
    return s


def normalized(text):
    """The words of a text, lower case, without punctuation. Two phrasings with the same
    normalized form count as the same: a candidate that only changes capitalization,
    punctuation or spacing is not a paraphrase (the retrievers ignore all three, so it would
    show zero jitter). Stricter than section 1.2's rule for A2 rewrites, which counts any
    punctuation change."""
    return " ".join(t for t in an.tokens(text) if t.isalnum())


def leaks_answer(paraphrase, original, answers):
    """True if some gold answer appears verbatim (DPR token match) in the paraphrase but not in
    the original. An answer already in the original (e.g. "which is older, X or Y?") cannot be
    held against the paraphrase."""
    return any(an.has_answer([a], paraphrase) and not an.has_answer([a], original)
               for a in answers)


def entailment_index(id2label):
    """Index of the ENTAILMENT class in a model config's id2label."""
    found = [int(i) for i, name in id2label.items() if name.upper() == "ENTAILMENT"]
    if len(found) != 1:
        raise ValueError(f"no unique ENTAILMENT label in {id2label}")
    return found[0]


def screen(question, answers, candidates, nli_fwd, nli_bwd, cosines, entail):
    """Gate results for one question's candidates, in generation order.

    candidates: cleaned candidate strings. nli_fwd[i] / nli_bwd[i]: class probabilities for
    (original -> candidate) and (candidate -> original); cosines[i]: embedding cosine;
    entail: index of the ENTAILMENT class. Returns one dict per candidate with each gate's
    outcome, "passed", and "reason" (the first gate it failed, or None). A candidate that is
    empty, identical to the original, or a repeat of an earlier candidate fails before the gates.
    """
    out, seen = [], {normalized(question)}
    for i, text in enumerate(candidates):
        r = {"text": text, "nli_fwd": float(nli_fwd[i][entail]),
             "nli_bwd": float(nli_bwd[i][entail]), "cosine": float(cosines[i])}
        r["entails"] = (int(np.argmax(nli_fwd[i])) == entail
                        and int(np.argmax(nli_bwd[i])) == entail)
        r["leak"] = leaks_answer(text, question, answers) if text else False
        if not text:
            reason = "empty"
        elif normalized(text) in seen:
            reason = "duplicate"
        elif not r["entails"]:
            reason = "nli"
        elif r["cosine"] < COSINE_MIN:
            reason = "cosine"
        elif r["leak"]:
            reason = "answer"
        else:
            reason = None
        if text:
            seen.add(normalized(text))
        r["reason"], r["passed"] = reason, reason is None
        out.append(r)
    return out


def select(screened, n=PER_CLUSTER):
    """The first n passing candidates' texts, in generation order (fewer if not enough pass)."""
    return [r["text"] for r in screened if r["passed"]][:n]


# ----------------------------------------------------------------------------- gate models

def _device():
    import torch

    return "cuda" if torch.cuda.is_available() else "cpu"


def load_nli(device=None):
    """Tokenizer and DeBERTa-MNLI model at the pinned revision, in eval mode."""
    from transformers import AutoModelForSequenceClassification, AutoTokenizer

    device = device or _device()
    tok = AutoTokenizer.from_pretrained(NLI_MODEL, revision=NLI_REVISION)
    model = AutoModelForSequenceClassification.from_pretrained(
        NLI_MODEL, revision=NLI_REVISION).to(device).eval()
    return tok, model


def nli_probs(premises, hypotheses, nli, batch_size=32):
    """Class probabilities (n, 3) for each (premise, hypothesis) pair."""
    import torch

    tok, model = nli
    device = next(model.parameters()).device
    out = []
    with torch.no_grad():
        for i in range(0, len(premises), batch_size):
            x = tok(list(premises[i:i + batch_size]), list(hypotheses[i:i + batch_size]),
                    padding=True, truncation=True, return_tensors="pt").to(device)
            out.append(torch.softmax(model(**x).logits.float(), -1).cpu().numpy())
    return np.concatenate(out) if out else np.empty((0, 3))


def load_embedder(device=None):
    """Tokenizer and all-mpnet-base-v2 at the pinned revision, in eval mode."""
    from transformers import AutoModel, AutoTokenizer

    device = device or _device()
    tok = AutoTokenizer.from_pretrained(EMBED_MODEL, revision=EMBED_REVISION)
    model = AutoModel.from_pretrained(EMBED_MODEL, revision=EMBED_REVISION).to(device).eval()
    return tok, model


def embed(texts, embedder, batch_size=64):
    """Unit-length sentence embeddings, mean-pooled over real tokens (as sentence-transformers
    does for this model)."""
    import torch

    tok, model = embedder
    device = next(model.parameters()).device
    out = []
    with torch.no_grad():
        for i in range(0, len(texts), batch_size):
            x = tok(list(texts[i:i + batch_size]), padding=True, truncation=True,
                    max_length=384, return_tensors="pt").to(device)
            h = model(**x).last_hidden_state
            m = x["attention_mask"].unsqueeze(-1).to(h.dtype)
            e = torch.nn.functional.normalize((h * m).sum(1) / m.sum(1), dim=-1)
            out.append(e.float().cpu().numpy())
    return np.concatenate(out) if out else np.empty((0, 768))
